export function translate(text, language) {
  if (language !== 'te' || typeof text !== 'string') return text
  if (te[text] || te[text.trim().toLowerCase()]) return te[text] || te[text.trim().toLowerCase()]
  return text.replace(/[A-Za-z]+(?:['’-][A-Za-z]+)*/g, (word) => te[word.toLowerCase()] || word)
}
